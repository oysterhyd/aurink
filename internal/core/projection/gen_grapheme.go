//go:build ignore

// Generate the pinned Unicode properties and conformance fixtures.
package main

import (
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"strconv"
	"strings"
)

const ucd = "https://www.unicode.org/Public/17.0.0/ucd/"

func fetch(url string) string {
	r, err := http.Get(url)
	if err != nil {
		panic(err)
	}
	defer r.Body.Close()
	if r.StatusCode != 200 {
		panic(r.Status)
	}
	b, err := io.ReadAll(r.Body)
	if err != nil {
		panic(err)
	}
	return string(b)
}

func main() {
	props := make([]uint16, 0x110000)
	names := map[string]uint16{"CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5, "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8, "L": 9, "V": 10, "T": 11}
	for _, file := range []string{"auxiliary/GraphemeBreakProperty.txt", "emoji/emoji-data.txt", "DerivedCoreProperties.txt"} {
		for line := range strings.SplitSeq(fetch(ucd+file), "\n") {
			line, _, _ = strings.Cut(line, "#")
			parts := strings.Split(line, ";")
			if len(parts) < 2 {
				continue
			}
			name := strings.TrimSpace(parts[1])
			var value uint16
			switch file {
			case "auxiliary/GraphemeBreakProperty.txt":
				value = names[name]
			case "emoji/emoji-data.txt":
				if name == "Extended_Pictographic" {
					value = 16
				}
			case "DerivedCoreProperties.txt":
				if name == "InCB" && len(parts) > 2 {
					value = map[string]uint16{"Consonant": 32, "Extend": 64, "Linker": 128}[strings.TrimSpace(parts[2])]
				}
			}
			if value == 0 {
				continue
			}
			span := strings.Split(strings.TrimSpace(parts[0]), "..")
			a, err := strconv.ParseUint(span[0], 16, 32)
			if err != nil {
				panic(err)
			}
			z := a
			if len(span) == 2 {
				z, err = strconv.ParseUint(span[1], 16, 32)
				if err != nil {
					panic(err)
				}
			}
			for i := a; i <= z; i++ {
				props[i] |= value
			}
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by go run gen_grapheme.go; DO NOT EDIT.\n// Unicode 17.0.0: GraphemeBreakProperty, emoji-data, DerivedCoreProperties.\n// https://www.unicode.org/Public/17.0.0/ucd/\n// Copyright Unicode, Inc. See testdata/LICENSE-Unicode.txt.\n\npackage projection\n\nvar graphemeProperties = [...]propertyRange{\n")
	for i := 0; i < len(props); i++ {
		if props[i] == 0 {
			continue
		}
		end := i
		for end+1 < len(props) && props[end+1] == props[i] {
			end++
		}
		fmt.Fprintf(&out, "{0x%X, 0x%X, %d},\n", i, end, props[i])
		i = end
	}
	out.WriteString("}\n")
	b, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("grapheme_tables.go", b, 0644); err != nil {
		panic(err)
	}
	if err = os.MkdirAll("testdata", 0755); err != nil {
		panic(err)
	}
	for name, url := range map[string]string{"GraphemeBreakTest.txt": ucd + "auxiliary/GraphemeBreakTest.txt", "LICENSE-Unicode.txt": "https://www.unicode.org/license.txt"} {
		if err = os.WriteFile("testdata/"+name, []byte(fetch(url)), 0644); err != nil {
			panic(err)
		}
	}
}
