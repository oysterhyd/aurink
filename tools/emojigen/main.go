// Command emojigen generates the Markdown shortcode table from gemoji.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
)

const release = "v4.1.0"
const dataURL = "https://raw.githubusercontent.com/github/gemoji/" + release + "/db/emoji.json"

func main() {
	resp, err := http.Get(dataURL)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatal(resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	var entries []struct {
		Emoji   string   `json:"emoji"`
		Aliases []string `json:"aliases"`
	}
	if err := json.Unmarshal(data, &entries); err != nil {
		log.Fatal(err)
	}
	aliases := make(map[string]string)
	for _, entry := range entries {
		for _, alias := range entry.Aliases {
			aliases[alias] = entry.Emoji
		}
	}
	keys := make([]string, 0, len(aliases))
	for key := range aliases {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by tools/emojigen; DO NOT EDIT.\n// gemoji %s db/emoji.json, SHA-256 %x.\n// See LICENSE-gemoji.txt.\n\npackage markdown\n\nvar emojiShortcodes = map[string]string{\n", release, sha256.Sum256(data))
	for _, key := range keys {
		fmt.Fprintf(&out, "\t%q: %q,\n", key, aliases[key])
	}
	out.WriteString("}\n")
	code, err := format.Source([]byte(out.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("internal/core/markdown/emoji_generated.go", code, 0644); err != nil {
		log.Fatal(err)
	}
}
